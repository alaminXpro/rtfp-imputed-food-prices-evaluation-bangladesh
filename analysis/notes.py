def note_t7():
    t = pd.read_csv(T / "T7_uncertainty.csv")
    qs = pd.read_csv(T / "T7c_quantile_scores.csv", index_col=0)
    chosen = qs.index[qs.chosen].item()
    a = t[(t.subset == "all")]
    aci = a[a.method == f"{chosen}+ACI"].set_index("nominal")
    stat = a[a.method == f"{chosen}+conformal"].set_index("nominal")
    band = a[a.method == "published_band"].iloc[0]
    d = pd.read_csv(sorted(T.glob("rtfp_bgd_calibrated_intervals_*.csv"))[-1])
    s = d[d.inside_support]
    txt = f"""# T7 — Calibrated uncertainty for imputed cells (Task 5.1)

*Generated by `analysis/notes.py` from `outputs/tables/T7_uncertainty.csv`, `T7c_quantile_scores.csv` and the interval file.*

**Claim 1.** The published high/low band is not an uncertainty interval for imputed cells: the later survey value falls inside it in {100 * band.coverage:.0f}% of test cells (mean band width {band.mean_width_logpts:.1f} log points).

**Claim 2.** Simple intervals, recalibrated online as each release reveals new survey values (adaptive conformal inference), reach nominal coverage on later releases: {100 * aci.loc[0.8, 'coverage']:.1f}% for the 80% interval (mean width {aci.loc[0.8, 'mean_width_logpts']:.1f} log points) and {100 * aci.loc[0.9, 'coverage']:.1f}% for the 90% interval ({aci.loc[0.9, 'mean_width_logpts']:.1f}). Calibrating once and holding the thresholds fixed under-covers ({100 * stat.loc[0.8, 'coverage']:.0f}% and {100 * stat.loc[0.9, 'coverage']:.0f}%), because the error distribution drifts across releases.

**Claim 3.** Covariates do not sharpen the intervals. The candidate chosen on a separate earlier block was `{chosen}`; the quantile gradient-boosting model scored worse on both the selection and the test block.

**Average quantile score (lower is better):**

{md(qs)}

**All methods (test block):**

{md(t[t.subset == 'all'][['nominal', 'method', 'selected', 'n_test', 'coverage', 'mean_width_logpts']])}

**Deliverable.** `{sorted(T.glob('rtfp_bgd_calibrated_intervals_*.csv'))[-1].name}`: {len(d):,} imputed cells in the latest release, of which {len(s):,} (price months {s.month.min()} to {s.month.max()}) lie inside the hold-out's covariate support and get intervals; median half-width {(50 * (s.hi80 / s.lo80 - 1)).median():.1f}% (80%) and {(50 * (s.hi90 / s.lo90 - 1)).median():.1f}% (90%). All other cells are flagged `inside_support = False` and get no interval.

**Method.** Target log(survey/imputed). Time split by the release in which the survey value arrived: train 60% | selection 10% | calibration 10% | test 20%. Conformalized quantile regression (Romano et al. 2019) with Mondrian groups (stratum × months since last report); ACI (Gibbs & Candès 2021), γ = 0.05, processing test releases in order. Closest prior method: Gui, Barber & Ma (2023).

**Caveats.** Exploratory. The test block is almost entirely forecast-stratum cells ({int(t[(t.method == f'{chosen}+conformal') & (t.nominal == 0.8) & (t.subset == 'forecast')].n_test.iloc[0])} forecast vs {int(t[(t.method == f'{chosen}+conformal') & (t.nominal == 0.8) & (t.subset == 'cross_sectional')].n_test.iloc[0])} cross-sectional cells), so coverage for cross-sectional cells is barely tested. Coverage is marginal, not per month (per-month coverage varies; T7b). Intervals target the reported survey value, not a latent true price.

**Files.** `outputs/tables/T7_uncertainty.csv`, `T7b_coverage_by_month.csv`, `T7c_quantile_scores.csv`, interval CSV; script `analysis/t7_uncertainty.py`.
"""
    (N / "T7.md").write_text(txt)


def note_t6():
    e = pd.read_csv(T / "T6_alerts.csv")
    z = pd.read_csv(T / "T6_alerts_zscores.csv")
    pw = pd.read_csv(T / "T6_alerts_power.csv")
    mt = pd.read_csv(T / "T6_alerts_benchmark_matched.csv")
    allr = e[e["item"] == "ALL"]
    w = allr[["indicator", "level", "n_ref_pos", "recall", "recall_lo", "recall_hi", "precision", "kappa"]].merge(
        mt.pivot_table(index=["indicator", "level"], columns="benchmark", values="recall_matched").reset_index(),
        on=["indicator", "level"])
    w["survey_alert_rate"] = w.n_ref_pos / allr.n.iloc[0]
    ipa = w[w.indicator != "alps"].copy()
    ipa["ci_contains_no_local"] = (ipa.recall_lo <= ipa.common_only) & (ipa.common_only <= ipa.recall_hi)
    ipa["ci_below_oracle"] = ipa.recall_hi < ipa.oracle_noise_removed
    n_in = int(ipa.ci_contains_no_local.sum())
    n_below = int(ipa.ci_below_oracle.sum())
    alps = w[w.indicator == "alps"].set_index("level")
    alps_rate = (z[z.indicator == "alps"].z_survey >= 1).mean()
    alps_mean = z[z.indicator == "alps"].z_survey.mean()
    counts = e[(e["item"] != "ALL") & e.indicator.str.startswith("ipa") & (e.level == "alert")][["item", "indicator", "n_ref_pos"]]
    txt = f"""# T6 — Do imputed prices raise the same early-warning alerts as survey prices? (Task 4.1)

*Generated by `analysis/notes.py` from `outputs/tables/T6_alerts*.csv` (script `analysis/t6_alerts.py`). Revised after independent verification: benchmarks are base-rate matched and pooled with empirical item weights; power uses bootstrap SEs.*

**Claim 1 (IPA, the discriminating indicator).** For FAO's Indicator of Price Anomalies, imputed values recover {rng(100 * ipa.recall, 0)}% of the alerts that the later survey value raises (pooled, clean hold-out). This is **statistically indistinguishable from a simulated value that carries no local information** ({rng(100 * ipa.common_only, 0)}%; the 95% interval contains that benchmark in {n_in} of {len(ipa)} rows), and below a simulated value that removes survey noise but keeps all local signal ({rng(100 * ipa.oracle_noise_removed, 0)}%; interval entirely below it in {n_below} of {len(ipa)} rows).

**Claim 2 (ALPS is uninformative in this period).** Survey values in the hold-out period sit on average {alps_mean:.2f} standard deviations above ALPS's long-run trend (fitted from 2007), so {100 * alps_rate:.0f}% of clean cells are already 'Alert or Crisis'. With base rates matched, a simulated value with no local information reaches ALPS recall {alps.loc['alert', 'common_only']:.2f} ('Alert') and {alps.loc['any', 'common_only']:.2f} ('any'), against {alps.loc['alert', 'recall']:.2f} and {alps.loc['any', 'recall']:.2f} for the imputed values: ALPS agreement says nothing about local information here.

**Pooled agreement and base-rate-matched benchmarks (recall):**

{md(w[['indicator', 'level', 'survey_alert_rate', 'n_ref_pos', 'recall', 'recall_lo', 'recall_hi', 'precision', 'kappa', 'common_only', 'oracle_noise_removed']])}

**Survey IPA alert counts by item** (small for rice and wheat flour):

{md(counts)}

**By item:**

{md(e[e['item'] != 'ALL'][['item', 'indicator', 'level', 'n', 'n_ref_pos', 'recall', 'recall_lo', 'recall_hi', 'precision', 'kappa']])}

**Power.** Smallest recall difference detectable at 80% power, from the bootstrap SE of recall (two-way clustering; the iid figure is shown for reference and is several times too optimistic):

{md(pw[pw['item'] == 'ALL'][['indicator', 'level', 'n_ref_pos', 'recall', 'recall_boot_se', 'detectable_recall_diff_80pct', 'iid_detectable_diff_for_reference']])}

**Method.** For each clean hold-out cell the month-t value (imputed `c_final`, or survey `y_eval`) is appended to the same history (latest release's published series, months < t) and classified with ALPS (WFP 2014) and IPA (Baquedano 2015, γ by PCA; SDG 2.c.1, γ = 0.4). Survey classes are the reference. CIs: two-way (market × month) pigeonhole bootstrap, 500 draws. Benchmarks: simulation calibrated to Bangladesh (Table A4), 50 panels per item, last 12 months; per item × indicator × level the simulated threshold is set to reproduce the empirical survey alert rate, and recall is pooled with empirical item weights.

**Caveats.**
- Exploratory. The benchmark comparison is indicative, not a test.
- History length differs: the simulation has 75 months from 2020-08 (about 6 years per calendar month for IPA and for the ALPS trend), the data 200–235 months from 2007.
- Monte Carlo error of the benchmark recall (50 panels) is about 0.01–0.03.
- Prices are nominal (IPA documents deflate); the history mixes survey and imputed values.
- Native (unmatched) benchmarks are in `T6_alerts_benchmark.csv`; they over-weight rice and wheat flour and inflate the no-local-information recall.

**Files.** `outputs/tables/T6_alerts.csv`, `T6_alerts_benchmark_matched.csv`, `T6_alerts_benchmark_matched_items.csv`, `T6_alerts_benchmark.csv`, `T6_alerts_power.csv`, `T6_alerts_zscores.csv`.
"""
    (N / "T6.md").write_text(txt)


