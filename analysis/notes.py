"""Generate results notes T2, T3, T4, T7 from the output tables (no hand-typed numbers).

Run after the corresponding analysis scripts. Each note: claim, key numbers, method, caveats, files.
"""
from pathlib import Path

import numpy as np
import pandas as pd

T = Path("outputs/tables")
N = Path("outputs/results_notes")


def md(df, digits=3):
    df = df.reset_index() if df.index.name or isinstance(df.index, pd.MultiIndex) else df
    cols = [str(c) for c in df.columns]
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in df.itertuples(index=False):
        out.append("| " + " | ".join("" if (isinstance(v, float) and np.isnan(v)) else
                                     (f"{v:.{digits}f}" if isinstance(v, float) else str(v)) for v in r) + " |")
    return "\n".join(out)


def rng(s, d=1):
    return f"{s.min():.{d}f}–{s.max():.{d}f}"


def note_t2():
    t = pd.read_csv(T / "T2_levels.csv")
    c = t[(t.estimate == "c_final") & t.stratum.isin(["cross_sectional", "forecast"])]
    tg = t[(t.estimate == "c_final") & (t.stratum == "toggle")]
    cols = ["item", "stratum", "n", "mape", "mape_lo", "mape_hi", "median_ape", "bias_logpct", "bias_lo", "bias_hi",
            "share_err_gt10", "mz_slope_month_demeaned", "corr_log_levels", "band_coverage"]
    txt = f"""# T2 — Level accuracy of imputed cells against later survey values (Task 2.2, levels)

*Generated by `analysis/notes.py` from `outputs/tables/T2_levels.csv`.*

**Claim.** On clean hold-out cells (imputed in one release, surveyed later, value confirmed by the WFP feed), RTFP's imputed price levels are close to the later survey value on average: mean absolute error {rng(c.mape)}% and median {rng(c.median_ape)}% across items and strata, with mean log bias between {c.bias_logpct.min():.1f}% and {c.bias_logpct.max():.1f}%. Share of cells off by more than 10%: {rng(100 * c.share_err_gt10, 0)}%.

**Level correlation depends on the time span, not on accuracy.** On toggle cells spanning 2007–2024 the correlation of log levels is {rng(tg.corr_log_levels, 2)} (similar to the 0.94–0.99 reported for Nigeria by Adewopo et al. 2025), while on the clean recent cells, with similar errors, it is {rng(c.corr_log_levels, 2)}. Long trends inflate level correlations.

**Cross-market calibration.** The month-demeaned level Mincer–Zarnowitz slope is {rng(c.mz_slope_month_demeaned, 2)}; below 1 means imputed differences between markets are larger than the surveyed ones.

**Published high/low band.** The later survey value lies inside the imputing release's [l_, h_] band in {rng(100 * c.band_coverage, 0)}% of clean cells (band half-width ≈ {rng(t[(t.estimate == 'c_final') & t.stratum.isin(['cross_sectional', 'forecast'])].band_halfwidth_pct, 1)}%).

{md(c[cols])}

**Method.** Truth = latest-release survey value (equals the WFP feed, Table A1). Imputed value = `c_final` (last release before the survey value appeared). CIs: two-way (market × month) pigeonhole bootstrap, 500 draws.

**Caveats.** Exploratory (pre-registration). Clean cells cover price months 2023-09 to 2026-08 only. The forecast stratum (no market observed in the imputing release's month) dominates the sample.

**Files.** `outputs/tables/T2_levels.csv`; script `analysis/t2_levels.py`.
"""
    (N / "T2.md").write_text(txt)


